const Ctx = createContext(null);
export const useLang = () => useContext(Ctx);

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(localStorage.getItem('zivv_lang') || 'ar');
  const isRTL = lang === 'ar';

  useEffect(() => {
    document.documentElement.dir = isRTL ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;
    localStorage.setItem('zivv_lang', lang);
  }, [lang, isRTL]);

  const setLang = (l) => setLangState(l === 'ar' ? 'ar' : 'en');
  const t = (k, n) => {
    let s = (dict[lang] && dict[lang][k]) || dict.en[k] || k;
    if (n !== undefined) s = s.replace('{n}', n);
    return s;
  };

  return <Ctx.Provider value={{ lang, setLang, t, isRTL }}>{children}</Ctx.Provider>;
}
